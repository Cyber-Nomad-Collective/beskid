#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { validateCurriculum } from "./validate-curriculum.mjs";

function catalogEntry(lesson, curriculumRoot) {
	const { metadata, path: lessonPath, check, body } = lesson;
	return {
		id: metadata.id,
		title: metadata.title,
		objective: metadata.objective,
		slug: lessonPath.split("/").at(-1),
		starterCode: fs.readFileSync(path.join(curriculumRoot, lessonPath, "start.bd"), "utf8").trimEnd(),
		command: metadata.command,
		mode: check.mode,
		hints: metadata.hints,
		lessonPath: `/site/learn/curriculum/${lessonPath}/lesson.md`,
		difficulty: metadata.difficulty,
		category: metadata.category,
		prerequisites: metadata.prerequisites,
		detailedContent: body,
		questions: metadata.questions,
		...(check.expectedOutput ? { expectedOutput: check.expectedOutput } : {}),
	};
}

export function renderGeneratedCatalog(lessons, curriculumRoot) {
	const catalog = lessons.map((lesson) => catalogEntry(lesson, curriculumRoot));
	return [
		"// Generated by scripts/build-curriculum.mjs. Do not edit by hand.",
		'import type { LearnExercise } from "./learningCatalog";',
		"",
		`export const generatedLearnExercises = ${JSON.stringify(catalog, null, "\t")} satisfies ReadonlyArray<LearnExercise>;`,
		"",
	].join("\n");
}

function main() {
	const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
	const learnRoot = path.resolve(scriptDirectory, "..");
	try {
		const curriculumRoot = path.join(learnRoot, "curriculum");
		const { lessons } = validateCurriculum({ curriculumRoot });
		const output = renderGeneratedCatalog(lessons, curriculumRoot);
		const outputPath = path.join(learnRoot, "src", "data", "generatedLearningCatalog.ts");
		if (process.argv.includes("--check")) {
			const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
			if (existing !== output) throw new Error(`${path.relative(learnRoot, outputPath)} is stale; run pnpm run curriculum:build`);
			console.log(`Generated catalog is current for ${lessons.length} authored lessons.`);
			return;
		}
		fs.writeFileSync(outputPath, output);
		console.log(`Generated ${path.relative(learnRoot, outputPath)} from ${lessons.length} authored lessons.`);
	} catch (error) {
		console.error(`Curriculum generation failed: ${error.message}`);
		process.exitCode = 1;
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
